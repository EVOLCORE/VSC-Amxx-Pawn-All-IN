        vscode,
        isPawnDocument,
        getPawnDocumentContext,
        resolvePersistentHoverTarget,
        getPersistentHoverMode,
        isPersistentHoverEnabled,
        getHoverMode,
        affectsAnyConfiguration,
        PERSISTENT_HOVER_RELEVANT_CONFIG_KEYS,
        computeFunctionRangeMaps
